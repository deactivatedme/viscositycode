#!/usr/bin/env node
// ViscosityCode: Apache-2.0 §4(b) housekeeping for the fork.
//
// 1. Every upstream file the fork has modified gets a one-line notice
//    ("Modified for ViscosityCode (fork of Poracode). See FORK_CHANGES.md.")
//    at the top, in the file's own comment syntax.
// 2. FORK_CHANGES.md is regenerated: modified upstream files and files the
//    fork added, grouped by top-level area.
//
// The comparison base is the merge-base with upstream/master, plus whatever is
// in the working tree (staged or not), so it can run right before a commit.
//   node scripts/viscosity/mark-modified-files.mjs          apply notices + write FORK_CHANGES.md
//   node scripts/viscosity/mark-modified-files.mjs --check  exit 1 if a notice or the list is stale
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const ROOT = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
const NOTICE = "Modified for ViscosityCode (fork of Poracode). See FORK_CHANGES.md.";
const CHECK = process.argv.includes("--check");

/** Files that are generated or whose bytes are pinned by a --check; never annotate them. */
const EXCLUDED = [
  /^src\/renderer\/locales\//,
  /^protocol\/.*\/generated\//,
  /\.generated\.(ts|tsx|js|mjs)$/,
  /^src\/build\/testDurations\.json$/,
  /^android\/app\/src\/main\/kotlin\/com\/poracode\/app\/ui\/theme\/PoracodeThemePresets\.kt$/,
  /^bun\.lock$/,
  /^FORK_CHANGES\.md$/,
];

const LINE = {
  ".ts": (t) => `// ${t}`,
  ".tsx": (t) => `// ${t}`,
  ".js": (t) => `// ${t}`,
  ".mjs": (t) => `// ${t}`,
  ".cjs": (t) => `// ${t}`,
  ".kt": (t) => `// ${t}`,
  ".swift": (t) => `// ${t}`,
  ".rs": (t) => `// ${t}`,
  ".css": (t) => `/* ${t} */`,
  ".html": (t) => `<!-- ${t} -->`,
  ".yml": (t) => `# ${t}`,
  ".yaml": (t) => `# ${t}`,
  ".toml": (t) => `# ${t}`,
  ".sh": (t) => `# ${t}`,
  ".nsh": (t) => `; ${t}`,
};

function git(args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
}

function changedFiles() {
  const base = git(["merge-base", "HEAD", "upstream/master"]).trim();
  const modified = new Set();
  const added = new Set();
  // Committed + working-tree changes relative to the upstream base.
  for (const line of git(["diff", "--name-status", "--no-renames", base]).split("\n")) {
    const [status, path] = line.split("\t");
    if (!path) continue;
    if (status === "M") modified.add(path);
    else if (status === "A") added.add(path);
  }
  for (const path of git(["ls-files", "--others", "--exclude-standard"]).split("\n")) {
    if (path) added.add(path);
  }
  return { modified: [...modified].sort(), added: [...added].sort() };
}

/** Insert the notice after a shebang / doctype, or at the very top. */
function annotate(source, comment) {
  if (source.includes(NOTICE)) return source;
  const lines = source.split("\n");
  const keepFirst = /^#!/.test(lines[0]) || /^<!doctype/i.test(lines[0]);
  if (keepFirst) {
    lines.splice(1, 0, comment);
    return lines.join("\n");
  }
  return `${comment}\n${source}`;
}

function area(path) {
  const [top, second] = path.split("/");
  return top === "src" && second ? `src/${second}` : top;
}

function renderList({ modified, added }) {
  const group = (paths) => {
    const by = new Map();
    for (const p of paths) by.set(area(p), [...(by.get(area(p)) ?? []), p]);
    return [...by.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, items]) => `### ${name}\n\n${items.map((p) => `- \`${p}\``).join("\n")}\n`)
      .join("\n");
  };
  return `# ViscosityCode fork changes

ViscosityCode is a modified version of [Poracode](https://github.com/Porabuild/Poracode),
licensed under the Apache License 2.0 (see \`LICENSE\` and \`NOTICE\`). As Apache-2.0 §4(b)
requires, every upstream file the fork changed carries the notice
"${NOTICE}" near its top (generated files and translation catalogs are listed here instead).

This file is generated by \`node scripts/viscosity/mark-modified-files.mjs\` — do not edit by hand.

## Modified upstream files (${modified.length})

${group(modified)}
## Files added by the fork (${added.length})

${group(added)}`;
}

const { modified, added } = changedFiles();
const stale = [];
for (const path of modified) {
  if (EXCLUDED.some((re) => re.test(path))) continue;
  const make = LINE[extname(path)];
  if (!make) continue;
  const file = join(ROOT, path);
  if (!existsSync(file)) continue;
  const source = readFileSync(file, "utf8");
  const next = annotate(source, make(NOTICE));
  if (next !== source) {
    stale.push(path);
    if (!CHECK) writeFileSync(file, next);
  }
}
const listPath = join(ROOT, "FORK_CHANGES.md");
const list = renderList({ modified, added: added.filter((p) => p !== "FORK_CHANGES.md") });
const listStale = !existsSync(listPath) || readFileSync(listPath, "utf8") !== list;
if (CHECK) {
  if (stale.length || listStale) {
    console.error(
      `${stale.length} modified file(s) lack the fork notice${listStale ? "; FORK_CHANGES.md is stale" : ""}.`,
    );
    for (const path of stale) console.error(`  - ${path}`);
    process.exit(1);
  }
  console.log("Fork notices and FORK_CHANGES.md are up to date.");
} else {
  writeFileSync(listPath, list);
  console.log(
    `Annotated ${stale.length} file(s); FORK_CHANGES.md lists ${modified.length} modified and ${added.length} added files.`,
  );
}
